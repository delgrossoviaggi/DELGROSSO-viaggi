import assert from 'node:assert/strict';
import fs from 'node:fs';
const html=fs.readFileSync('GESTIONALE/index.html','utf8');
const vercel=JSON.parse(fs.readFileSync('vercel.json','utf8'));
assert(!html.includes('<base href="/GESTIONALE/">'),'Do not override original V2 relative paths globally');
assert(html.includes('data-src="/GESTIONALE/suite/index.html"'),'V2 must embed correct absolute Business Suite path');
assert(html.includes('src="/GESTIONALE/delgrosso-logo-originale-bianco.png"'),'Header must use original logo absolute path');
for(const path of ['GESTIONALE/suite/index.html','GESTIONALE/delgrosso-logo-originale-bianco.png'])assert(fs.existsSync(path),'Required static asset absent: '+path);
assert(!vercel.redirects||vercel.redirects.length===0,'Avoid DG38 redirects that disrupted production routes');
assert(vercel.headers.some(x=>x.headers.some(h=>h.key==='X-Frame-Options'&&h.value==='SAMEORIGIN')),'Preserve same-origin iframe protection');
console.log('DG40 PASS: V2 static logo and Suite paths, no global base override or disruptive redirects.');
